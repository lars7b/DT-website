using Microsoft.AspNetCore.Hosting;
using Microsoft.AspNetCore.Mvc.Testing;
using Microsoft.Extensions.Configuration;
using Testcontainers.PostgreSql;
using Testcontainers.Redis;
using Xunit;
using Npgsql;
using System.Threading.Tasks;

namespace Backend.Tests.IntegrationTests;

public class CustomApiFactory : WebApplicationFactory<Program>, IAsyncLifetime
{
    private readonly PostgreSqlContainer _dbContainer = new PostgreSqlBuilder()
        .WithImage("postgres:15-alpine")
        .WithDatabase("test_db")
        .WithUsername("postgres")
        .WithPassword("postgres")
        .Build();

    private readonly RedisContainer _redisContainer = new RedisBuilder()
        .WithImage("redis:7-alpine")
        .Build();

    public CustomApiFactory()
    {
        Environment.SetEnvironmentVariable("JWT_SECRET_KEY", "A_Very_Long_Super_Secret_Key_For_Testing_Only_12345!");
        Environment.SetEnvironmentVariable("JwtSettings__Key", "A_Very_Long_Super_Secret_Key_For_Testing_Only_12345!");
        Environment.SetEnvironmentVariable("JwtSettings__Issuer", "TestIssuer");
        Environment.SetEnvironmentVariable("JwtSettings__Audience", "TestAudience");
    }

    public async ValueTask InitializeAsync()
    {
        await Task.WhenAll(_dbContainer.StartAsync(), _redisContainer.StartAsync());

        await InitializeDatabaseAsync();
    }

    private async Task InitializeDatabaseAsync()
    {
        var connectionString = _dbContainer.GetConnectionString();
        await using var connection = new NpgsqlConnection(connectionString);
        await connection.OpenAsync();

        // Testdatabase schema.
        // Deze tabellen zijn nodig voor de bestaande auth/employee tests
        // en voor de products/reviews integration tests.
        var sql = @"
            CREATE TABLE IF NOT EXISTS ""users"" (
                ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""email"" VARCHAR(100) UNIQUE NOT NULL,
                ""password_hash"" VARCHAR(255) NOT NULL,
                ""role"" VARCHAR(20) DEFAULT 'Customer'
            );

            CREATE TABLE IF NOT EXISTS ""customers"" (
                ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""user_id"" INT UNIQUE NOT NULL,
                ""first_name"" VARCHAR(50),
                ""last_name"" VARCHAR(50),
                ""phone"" VARCHAR(20) UNIQUE,
                ""address"" VARCHAR(200),
                CONSTRAINT ""fk_customers_user""
                    FOREIGN KEY (""user_id"") 
                    REFERENCES ""users"" (""id"")
                    ON DELETE CASCADE
            );

            CREATE TABLE IF NOT EXISTS ""employees"" (
                ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""user_id"" INT UNIQUE NOT NULL,
                ""first_name"" VARCHAR(50) NOT NULL,
                ""last_name"" VARCHAR(50) NOT NULL,
                ""phone"" VARCHAR(20) UNIQUE,
                ""position"" VARCHAR(50),
                CONSTRAINT ""fk_employees_user""
                    FOREIGN KEY (""user_id"") 
                    REFERENCES ""users"" (""id"")
                    ON DELETE CASCADE
            );

            CREATE TABLE IF NOT EXISTS ""products"" (
                ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""name"" VARCHAR(150) NOT NULL,
                ""description"" TEXT,
                ""price"" DECIMAL(10,2) NOT NULL,
                ""category_id"" INT,
                ""subcategory_id"" INT
            );

            CREATE TABLE IF NOT EXISTS ""reviews"" (
                ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                ""customer_id"" INT NOT NULL,
                ""product_id"" INT NOT NULL,
                ""rating"" INT NOT NULL,
                ""comment"" VARCHAR(100),
                ""review_date"" DATE DEFAULT CURRENT_DATE,
                CONSTRAINT ""fk_reviews_customer""
                    FOREIGN KEY (""customer_id"")
                    REFERENCES ""customers"" (""id"")
                    ON DELETE CASCADE,
                CONSTRAINT ""fk_reviews_product""
                    FOREIGN KEY (""product_id"")
                    REFERENCES ""products"" (""id"")
                    ON DELETE CASCADE
            );

            CREATE TABLE IF NOT EXISTS ""categories"" (
            ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ""name"" VARCHAR(100) NOT NULL
            );

            CREATE TABLE IF NOT EXISTS ""subcategories"" (
            ""id"" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            ""category_id"" INT NOT NULL,
            ""name"" VARCHAR(100) NOT NULL,
            CONSTRAINT ""fk_subcategories_category""
                FOREIGN KEY (""category_id"")                    
                REFERENCES ""categories"" (""id"")
                ON DELETE CASCADE
            );
        ";

        await using var command = new NpgsqlCommand(sql, connection);
        await command.ExecuteNonQueryAsync();
    }

    // Overschrijf de config, pak de connectionstring van test_db
    protected override void ConfigureWebHost(IWebHostBuilder builder)
    {
        builder.ConfigureAppConfiguration((context, config) =>
        {
            config.AddInMemoryCollection(new Dictionary<string, string?>
            {
                { "ConnectionStrings:DefaultConnection", _dbContainer.GetConnectionString() },
                { "ConnectionStrings:RedisDefaultConnection", _redisContainer.GetConnectionString() },

                { "DB_PASSWORD", "dummy_db_password" },
                { "REDIS_PASSWORD", "dummy_redis_password" },

                { "JWT_SECRET_KEY", "A_Very_Long_Super_Secret_Key_For_Testing_Only_12345!" },
                { "JwtSettings:Key", "A_Very_Long_Super_Secret_Key_For_Testing_Only_12345!" },
                { "JwtSettings:Issuer", "TestIssuer" },
                { "JwtSettings:Audience", "TestAudience" }
            });
        });
    }

    public new async ValueTask DisposeAsync()
    {
        await _dbContainer.DisposeAsync();
        await _redisContainer.DisposeAsync();
    }
}
